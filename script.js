function cajaVerde(event) {
    let container = event.target.closest('.cards-container');

    // Comparar usando el valor en RGB
    if (container.style.backgroundColor === "rgb(102, 187, 106)") { 
        container.style.backgroundColor = "#4CAF50"; 
    } else {
        container.style.backgroundColor = "#66BB6A"; 
    }
}

